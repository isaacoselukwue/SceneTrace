import type { AnalysisOut, InvestigationOut, RunMode } from "../api/client";
import { dateTime, STATUS_LABELS, usd } from "../lib/format";
import { Icon, type IconName } from "./Icons";

const MODE_TEXT: Record<RunMode, string> = {
  fixture: "Development fixture",
  recorded_real: "Recorded real run",
  live: "Live analysis",
};
export const STATUS_ICON: Record<string, IconName> = {
  supported: "check",
  plausible: "help",
  contested: "alert",
  rejected: "x",
  pending: "clock",
};

export function RunModeBadge({ mode }: { mode: RunMode }) {
  return (
    <span className={`badge mode-${mode}`}>
      <span className="badge-dot" aria-hidden="true" /> {MODE_TEXT[mode]}
    </span>
  );
}

export function StatusBadge({ status }: { status: string }) {
  return (
    <span className={`badge status-${status}`}>
      <Icon name={STATUS_ICON[status] ?? "info"} size={13} /> {STATUS_LABELS[status] ?? status}
    </span>
  );
}

export function ReviewBadge({ investigation }: { investigation: InvestigationOut }) {
  const { review_mode: mode, review_verdict: verdict } = investigation;
  const text =
    mode === "not_run" ? "Secondary review not run"
      : verdict === "unavailable" ? "Secondary review unavailable"
        : `Muse Wonder review${mode === "image_secondary" ? " with images" : ", text only"}: ${verdict.replace("_", " ")}`;
  const tone = mode === "not_run" ? "neutral" : verdict === "pass" ? "ok" : verdict === "unavailable" ? "warn" : "bad";
  return <span className={`badge tone-${tone}`}>{text}</span>;
}

export function ModeBanner({ analysis }: { analysis: AnalysisOut }) {
  return (
    <div className="banners">
      {analysis.run_mode === "fixture" && (
        <div className="banner banner-fixture" role="status">
          <Icon name="alert" size={18} />
          <p><strong>Development fixture. Not a real video analysis.</strong> Tracks and assessments are generated by deterministic code.</p>
        </div>
      )}
      {analysis.run_mode === "recorded_real" && (
        <div className="banner banner-recorded" role="status">
          <Icon name="film" size={18} />
          <p>
            <strong>Recorded investigation.</strong> Originally processed {dateTime(analysis.provenance.recorded_at)} with{" "}
            {Object.values(analysis.provenance.models).join(", ")}. Replayed without new model calls. Original processing
            cost {usd(analysis.usage.total_microusd)}.
          </p>
        </div>
      )}
      {analysis.media_kind === "synthetic_render" && (
        <div className="banner banner-synthetic" role="note">
          <Icon name="info" size={18} />
          <p><strong>Synthetic test animation.</strong> A drawing made for testing, not real footage; its results are not real-video evidence.</p>
        </div>
      )}
    </div>
  );
}
